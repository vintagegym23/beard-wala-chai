// Icons scale with the surrounding font size; default to 24px when no size class is given.
const SIZE_CLASS = /(^|\s)text-(\[\d|xs|sm|base|lg|xl|\dxl)/;

interface IconProps {
  name: string;
  className?: string;
  title?: string;
}

export default function Icon({ name, className = '', title }: IconProps) {
  const Glyph = icons[name] ?? CircleHelp;
  const classes = `inline-block shrink-0 ${SIZE_CLASS.test(className) ? '' : 'text-2xl '}${className}`.trim();
  const svg = <Glyph size="1em" strokeWidth={2} aria-hidden="true" className={classes} />;
  return title ? <span title={title}>{svg}</span> : svg;
}
